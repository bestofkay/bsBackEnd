-- MySQL schema for statements, transactions, analyses (reference archive)

CREATE TABLE `statements` (
    `id` VARCHAR(191) NOT NULL,
    `reference_id` VARCHAR(32) NULL,
    `document_hash` VARCHAR(128) NULL,
    `source_type` VARCHAR(32) NOT NULL,
    `source_url` TEXT NULL,
    `source_filename` VARCHAR(512) NULL,
    `mime_type` VARCHAR(128) NULL,
    `content_hash` VARCHAR(128) NULL,
    `bank_name` VARCHAR(255) NULL,
    `account_name` VARCHAR(255) NULL,
    `owner_name` VARCHAR(255) NULL,
    `masked_account_number` VARCHAR(64) NULL,
    `account_number` VARCHAR(64) NULL,
    `account_type` VARCHAR(128) NULL,
    `currency` VARCHAR(8) NULL,
    `period_from` DATETIME(3) NULL,
    `period_to` DATETIME(3) NULL,
    `analysis_from` DATETIME(3) NULL,
    `analysis_to` DATETIME(3) NULL,
    `statement_period_start` DATETIME(3) NULL,
    `statement_period_end` DATETIME(3) NULL,
    `opening_balance` DECIMAL(18, 4) NULL,
    `closing_balance` DECIMAL(18, 4) NULL,
    `processing_status` VARCHAR(32) NOT NULL DEFAULT 'COMPLETED',
    `extraction_engine_version` VARCHAR(32) NULL,
    `parser_version` VARCHAR(32) NULL,
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updated_at` DATETIME(3) NOT NULL,

    PRIMARY KEY (`id`),
    UNIQUE INDEX `statements_reference_id_key`(`reference_id`),
    INDEX `statements_document_hash_idx`(`document_hash`),
    INDEX `statements_content_hash_idx`(`content_hash`),
    INDEX `statements_processing_status_idx`(`processing_status`),
    INDEX `statements_created_at_idx`(`created_at`),
    INDEX `statements_owner_name_idx`(`owner_name`),
    INDEX `statements_account_name_idx`(`account_name`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `transactions` (
    `id` VARCHAR(191) NOT NULL,
    `statement_id` VARCHAR(191) NOT NULL,
    `transaction_date` DATETIME(3) NULL,
    `value_date` DATETIME(3) NULL,
    `posting_date` DATETIME(3) NULL,
    `description` TEXT NULL,
    `reference` VARCHAR(255) NULL,
    `debit` DECIMAL(18, 4) NULL,
    `credit` DECIMAL(18, 4) NULL,
    `amount` DECIMAL(18, 4) NULL,
    `balance` DECIMAL(18, 4) NULL,
    `currency` VARCHAR(8) NULL,
    `transaction_type` VARCHAR(64) NULL,
    `confidence` DECIMAL(5, 4) NULL,
    `duplicate_status` VARCHAR(64) NULL,
    `fingerprint` VARCHAR(128) NULL,
    `raw_json` JSON NULL,
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    PRIMARY KEY (`id`),
    INDEX `transactions_statement_id_idx`(`statement_id`),
    INDEX `transactions_fingerprint_idx`(`fingerprint`),
    INDEX `transactions_transaction_date_idx`(`transaction_date`),
    INDEX `transactions_reference_idx`(`reference`),
    INDEX `transactions_amount_idx`(`amount`),
    INDEX `transactions_transaction_type_idx`(`transaction_type`),
    CONSTRAINT `transactions_statement_id_fkey` FOREIGN KEY (`statement_id`) REFERENCES `statements`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `analyses` (
    `id` VARCHAR(191) NOT NULL,
    `statement_id` VARCHAR(191) NOT NULL,
    `reference_id` VARCHAR(32) NOT NULL,
    `owner_name` VARCHAR(255) NULL,
    `account_name` VARCHAR(255) NULL,
    `bank_name` VARCHAR(255) NULL,
    `account_number` VARCHAR(64) NULL,
    `score` INTEGER NULL,
    `score_band` VARCHAR(32) NULL,
    `recommendation` VARCHAR(64) NULL,
    `period_from` DATETIME(3) NULL,
    `period_to` DATETIME(3) NULL,
    `analysis_from` DATETIME(3) NULL,
    `analysis_to` DATETIME(3) NULL,
    `scoped_tx_count` INTEGER NULL,
    `full_tx_count` INTEGER NULL,
    `source` VARCHAR(32) NULL,
    `filename` VARCHAR(512) NULL,
    `run_id` VARCHAR(64) NULL,
    `analysis_json` JSON NOT NULL,
    `public_result_json` JSON NOT NULL,
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updated_at` DATETIME(3) NOT NULL,

    PRIMARY KEY (`id`),
    UNIQUE INDEX `analyses_reference_id_key`(`reference_id`),
    INDEX `analyses_owner_name_idx`(`owner_name`),
    INDEX `analyses_account_name_idx`(`account_name`),
    INDEX `analyses_created_at_idx`(`created_at`),
    INDEX `analyses_statement_id_idx`(`statement_id`),
    CONSTRAINT `analyses_statement_id_fkey` FOREIGN KEY (`statement_id`) REFERENCES `statements`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `extraction_runs` (
    `id` VARCHAR(191) NOT NULL,
    `statement_id` VARCHAR(191) NULL,
    `run_id` VARCHAR(64) NULL,
    `status` VARCHAR(32) NOT NULL,
    `source_type` VARCHAR(32) NOT NULL,
    `input_hash` VARCHAR(128) NULL,
    `extraction_method` VARCHAR(64) NULL,
    `parser` VARCHAR(64) NULL,
    `ocr_used` BOOLEAN NOT NULL DEFAULT false,
    `processing_time_ms` INTEGER NULL,
    `page_count` INTEGER NULL,
    `success` BOOLEAN NOT NULL DEFAULT false,
    `error_code` VARCHAR(64) NULL,
    `error_message` TEXT NULL,
    `confidence` DECIMAL(5, 4) NULL,
    `transaction_count` INTEGER NULL,
    `engine_version` VARCHAR(32) NULL,
    `started_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `finished_at` DATETIME(3) NULL,
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `result_json` JSON NULL,

    PRIMARY KEY (`id`),
    UNIQUE INDEX `extraction_runs_run_id_key`(`run_id`),
    INDEX `extraction_runs_statement_id_idx`(`statement_id`),
    INDEX `extraction_runs_status_idx`(`status`),
    INDEX `extraction_runs_started_at_idx`(`started_at`),
    INDEX `extraction_runs_created_at_idx`(`created_at`),
    CONSTRAINT `extraction_runs_statement_id_fkey` FOREIGN KEY (`statement_id`) REFERENCES `statements`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `validation_results` (
    `id` VARCHAR(191) NOT NULL,
    `statement_id` VARCHAR(191) NULL,
    `extraction_run_id` VARCHAR(191) NOT NULL,
    `reconciled` BOOLEAN NOT NULL DEFAULT false,
    `calculated_closing_balance` DECIMAL(18, 4) NULL,
    `statement_closing_balance` DECIMAL(18, 4) NULL,
    `difference` DECIMAL(18, 4) NULL,
    `validation_status` VARCHAR(64) NOT NULL,
    `is_valid` BOOLEAN NOT NULL,
    `warnings_json` JSON NULL,
    `issues_json` JSON NOT NULL,
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `checked_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    PRIMARY KEY (`id`),
    INDEX `validation_results_statement_id_idx`(`statement_id`),
    INDEX `validation_results_extraction_run_id_idx`(`extraction_run_id`),
    CONSTRAINT `validation_results_statement_id_fkey` FOREIGN KEY (`statement_id`) REFERENCES `statements`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `validation_results_extraction_run_id_fkey` FOREIGN KEY (`extraction_run_id`) REFERENCES `extraction_runs`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
